create or replace view shipping.pending_yampi_orders as
select
  yo.id as yampi_row_id,
  yo.merchant_id,
  yo.yampi_order_id,
  yo.order_number,
  yo.integration_event_id,
  yo.payment_status,
  yo.total_cents,
  yo.shipping_cents,
  yo.source_created_at,
  yc.name as customer_name,
  yc.email as customer_email,
  yc.phone_full_number as customer_phone,
  yc.cpf as customer_cpf,
  ya.receiver as shipping_name,
  ya.street as shipping_address,
  ya.street_number as shipping_number,
  ya.complement as shipping_complement,
  ya.neighborhood as shipping_neighborhood,
  ya.city as shipping_city,
  ya.state as shipping_state,
  ya.zipcode as shipping_zip,
  ya.country as shipping_country
from yampi.orders yo
left join yampi.customers yc on yc.id = yo.yampi_customer_ref_id
left join yampi.order_addresses ya
  on ya.merchant_id = yo.merchant_id
  and ya.yampi_order_id = yo.yampi_order_id
  and ya.address_type = 'shipping'
where yo.payment_status in ('paid', 'aprovado', 'approved')
  and not exists (
    select 1 from shipping.unified_orders uo
    where uo.source_platform = 'yampi'
      and uo.source_order_id = yo.yampi_order_id::text
  );

create or replace view shipping.pending_cartpanda_orders as
select
  co.id as cartpanda_row_id,
  co.shop_id,
  co.cartpanda_order_id,
  co.order_number,
  co.integration_event_id,
  co.payment_status,
  co.total_cents,
  co.shipping_cents,
  co.source_created_at,
  cc.full_name as customer_name,
  cc.email as customer_email,
  cc.phone as customer_phone,
  cc.cpf as customer_cpf,
  ca.name as shipping_name,
  ca.address1 as shipping_address,
  ca.house_no as shipping_number,
  ca.compartment as shipping_complement,
  ca.neighborhood as shipping_neighborhood,
  ca.city as shipping_city,
  ca.province_code as shipping_state,
  ca.zip as shipping_zip,
  ca.country_code as shipping_country
from cartpanda.orders co
left join cartpanda.customers cc on cc.id = co.customer_ref_id
left join cartpanda.order_addresses ca
  on ca.shop_id = co.shop_id
  and ca.cartpanda_order_id = co.cartpanda_order_id
  and ca.address_type = 'shipping'
where co.payment_status in ('paid', 'aprovado', 'approved')
  and not exists (
    select 1 from shipping.unified_orders uo
    where uo.source_platform = 'cartpanda'
      and uo.source_order_id = co.cartpanda_order_id::text
  );

