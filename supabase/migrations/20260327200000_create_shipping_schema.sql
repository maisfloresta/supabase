-- =============================================================================
-- shipping.product_dimensions — Catálogo de dimensões dos produtos
-- =============================================================================

create table if not exists shipping.product_dimensions (
  id bigint generated by default as identity primary key,
  store_id uuid references integrations.stores(id) on delete set null,
  sku text not null,
  product_name text not null,
  weight_grams integer not null default 0 check (weight_grams >= 0),
  height_cm numeric(8,2) not null default 0 check (height_cm >= 0),
  width_cm numeric(8,2) not null default 0 check (width_cm >= 0),
  length_cm numeric(8,2) not null default 0 check (length_cm >= 0),
  source_platform text check (source_platform in ('yampi', 'cartpanda', 'abacatepay', 'appmax')),
  source_product_id text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, sku)
);

create index if not exists idx_shipping_product_dimensions_sku
  on shipping.product_dimensions (sku);
create index if not exists idx_shipping_product_dimensions_store
  on shipping.product_dimensions (store_id);
create index if not exists idx_shipping_product_dimensions_source
  on shipping.product_dimensions (source_platform, source_product_id);

drop trigger if exists trg_shipping_product_dimensions_updated_at on shipping.product_dimensions;
create trigger trg_shipping_product_dimensions_updated_at
before update on shipping.product_dimensions
for each row execute function integrations.set_updated_at();

-- =============================================================================
-- shipping.unified_orders — Pedidos unificados de todas as plataformas
-- =============================================================================

create table if not exists shipping.unified_orders (
  id bigint generated by default as identity primary key,
  order_uuid uuid not null unique default gen_random_uuid(),
  store_id uuid references integrations.stores(id) on delete set null,

  -- Origem do pedido
  source_platform text not null
    check (source_platform in ('yampi', 'cartpanda', 'abacatepay', 'appmax')),
  source_order_id text not null,
  source_order_number text,
  source_event_id bigint references integrations.integration_events(id) on delete set null,

  -- Cliente
  customer_name text,
  customer_email text,
  customer_phone text,
  customer_cpf text,

  -- Endereço de envio
  shipping_name text,
  shipping_address text,
  shipping_number text,
  shipping_complement text,
  shipping_neighborhood text,
  shipping_city text,
  shipping_state text,
  shipping_zip text,
  shipping_country text not null default 'BR',

  -- Itens (jsonb array)
  items jsonb not null default '[]'::jsonb,

  -- Dimensões do pacote (calculadas)
  package_weight_grams integer not null default 0 check (package_weight_grams >= 0),
  package_height_cm numeric(8,2) not null default 0 check (package_height_cm >= 0),
  package_width_cm numeric(8,2) not null default 0 check (package_width_cm >= 0),
  package_length_cm numeric(8,2) not null default 0 check (package_length_cm >= 0),

  -- Valores
  total_cents integer not null default 0,
  shipping_cents integer not null default 0,

  -- Status do pedido
  status text not null default 'pending'
    check (status in (
      'pending',           -- Recebido, aguardando cotação
      'quoted',            -- Cotação realizada
      'approved',          -- Cotação aprovada, aguardando compra de etiqueta
      'label_purchased',   -- Etiqueta comprada
      'separating',        -- Em separação
      'shipped',           -- Enviado
      'in_transit',        -- Em trânsito
      'delivered',         -- Entregue
      'cancelled',         -- Cancelado
      'returned'           -- Devolvido
    )),

  -- Timestamps de cada etapa
  quoted_at timestamptz,
  approved_at timestamptz,
  label_at timestamptz,
  separated_at timestamptz,
  shipped_at timestamptz,
  delivered_at timestamptz,
  cancelled_at timestamptz,

  -- Observações
  notes text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- Evita duplicidade: um pedido de uma plataforma só pode ser unificado uma vez
  unique (source_platform, source_order_id)
);

create index if not exists idx_shipping_unified_orders_status
  on shipping.unified_orders (status);
create index if not exists idx_shipping_unified_orders_platform
  on shipping.unified_orders (source_platform);
create index if not exists idx_shipping_unified_orders_store
  on shipping.unified_orders (store_id);
create index if not exists idx_shipping_unified_orders_created
  on shipping.unified_orders (created_at desc);
create index if not exists idx_shipping_unified_orders_customer_email
  on shipping.unified_orders (lower(customer_email));
create index if not exists idx_shipping_unified_orders_zip
  on shipping.unified_orders (shipping_zip);

drop trigger if exists trg_shipping_unified_orders_updated_at on shipping.unified_orders;
create trigger trg_shipping_unified_orders_updated_at
before update on shipping.unified_orders
for each row execute function integrations.set_updated_at();

-- =============================================================================
-- shipping.quotes — Cotações de frete
-- =============================================================================

create table if not exists shipping.quotes (
  id bigint generated by default as identity primary key,
  order_id bigint not null references shipping.unified_orders(id) on delete cascade,

  -- Provedor e transportadora
  carrier_provider text not null
    check (carrier_provider in ('correios', 'melhor_envio', 'kangu', 'frenet', 'manual')),
  carrier_name text not null,
  carrier_service_code text,
  external_service_id text,

  -- Valores
  price_cents integer not null default 0 check (price_cents >= 0),
  discount_cents integer not null default 0 check (discount_cents >= 0),
  final_price_cents integer not null default 0 check (final_price_cents >= 0),

  -- Prazo de entrega
  delivery_min_days integer,
  delivery_max_days integer,

  -- Seleção
  selected boolean not null default false,
  auto_selected boolean not null default false,

  -- Validade
  expires_at timestamptz,

  -- Resposta crua da API
  raw_response jsonb,

  created_at timestamptz not null default now()
);

create index if not exists idx_shipping_quotes_order
  on shipping.quotes (order_id);
create index if not exists idx_shipping_quotes_selected
  on shipping.quotes (order_id) where selected = true;

-- =============================================================================
-- shipping.labels — Etiquetas de envio
-- =============================================================================

create table if not exists shipping.labels (
  id bigint generated by default as identity primary key,
  order_id bigint not null references shipping.unified_orders(id) on delete cascade,
  quote_id bigint references shipping.quotes(id) on delete set null,

  -- Provedor e IDs externos
  carrier_provider text not null
    check (carrier_provider in ('correios', 'melhor_envio', 'kangu', 'frenet', 'manual')),
  external_label_id text,
  external_order_id text,

  -- Transportadora
  carrier_name text,
  service_name text,

  -- Rastreio
  tracking_code text,
  tracking_url text,

  -- Etiqueta (PDF)
  label_url text,

  -- Valor
  price_cents integer not null default 0 check (price_cents >= 0),

  -- Status
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'ready', 'printed', 'cancelled')),

  -- Timestamps
  purchased_at timestamptz,
  printed_at timestamptz,
  cancelled_at timestamptz,

  -- Resposta crua
  raw_response jsonb,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

